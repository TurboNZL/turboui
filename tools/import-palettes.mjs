// Turns turbothemes palettes (TurboNZL/turboengine, themes/) into TurboUI palette files.
//   node tools/import-palettes.mjs <path to turboengine/themes> <out dir> <palette id>...
// It runs the engine's own colour derivation (engine/src/palette.ts), so the colours are exactly the ones the web themes show.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const [themesDir, outDir, ...ids] = process.argv.slice(2);
if (!themesDir || !outDir || ids.length === 0) {
  console.error('usage: node tools/import-palettes.mjs <turboengine/themes> <out dir> <palette id>...');
  process.exit(1);
}
const { buildPalette, tokens } = await import(pathToFileURL(join(themesDir, 'engine/src/palette.ts')).href);

const specs = new Map();
for (const dir of readdirSync(join(themesDir, 'themes'), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  let json;
  try { json = JSON.parse(readFileSync(join(themesDir, 'themes', dir.name, 'theme.json'), 'utf8')); } catch { continue; }
  for (const p of json.palettes ?? []) specs.set(p.id, p);
}

// "h s% l%" -> "#rrggbb"
const hex = (triplet) => {
  const m = triplet.match(/^\s*(-?[\d.]+)\s+([\d.]+)%\s+([\d.]+)%\s*$/);
  if (!m) throw new Error(`not an HSL triplet: ${triplet}`);
  const h = ((parseFloat(m[1]) % 360) + 360) % 360, s = parseFloat(m[2]) / 100, l = parseFloat(m[3]) / 100;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => { const k = (n + h / 30) % 12; return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)); };
  return '#' + [f(0), f(8), f(4)].map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('');
};

mkdirSync(outDir, { recursive: true });
for (const id of ids) {
  const spec = specs.get(id);
  if (!spec) { console.error(`no palette called "${id}"`); process.exit(1); }
  const p = buildPalette(spec);
  const t = tokens(p);
  const lines = [
    `# Generated by tools/import-palettes.mjs from the turbothemes palette "${id}". Do not edit by hand.`,
    `name = ${JSON.stringify(spec.label)}`,
    `mode = ${JSON.stringify(p.dark ? 'dark' : 'light')}`,
    '',
    '[colors]',
    ...Object.entries(t).map(([k, v]) => `${k} = "${hex(v)}"`),
    '',
  ];
  writeFileSync(join(outDir, `${id}.toml`), lines.join('\n'));
  console.log(`${id}: ${spec.label} (${p.dark ? 'dark' : 'light'})`);
}
